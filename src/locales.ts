export type CollabTranslate = (key: CollabLocaleKey, params?: Record<string, unknown>) => string;

function interpolate(template: string, params?: Record<string, unknown>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match);
}

/** English fallback used by isolated component tests outside the DSH locale service. */
export const defaultCollabTranslate: CollabTranslate = (key, params) => interpolate(en[key], params);
